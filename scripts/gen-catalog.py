#!/usr/bin/env python3
"""Generates docs/CATALOG.md from the header blocks of every module.

Usage: python scripts/gen-catalog.py          (writes docs/CATALOG.md)
       python scripts/gen-catalog.py --check  (exit 1 if the file is stale)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIRS = ("core", "hardware", "i18n", "projects")
OUT = ROOT / "docs" / "CATALOG.md"
FIELD = re.compile(r"^# (Purpose|Requires|Chip):\s*(.*)$")


def header(path):
    info = {}
    for line in path.read_text(encoding="utf-8").splitlines()[:15]:
        m = FIELD.match(line)
        if m:
            info[m.group(1)] = m.group(2).strip()
    return info


def cell(text):
    return text.replace("|", "\\|") if text else ""


def build():
    out = ["# Catalog", "",
           "Generated by `python scripts/gen-catalog.py` from the header block of every file - do not edit by hand.", ""]
    for d in DIRS:
        base = ROOT / d
        if not base.is_dir():
            continue
        out += [f"## {d}/", "", "| File | Purpose | Chip | Requires |", "|---|---|---|---|"]
        for path in sorted(base.rglob("*.yaml")):
            info = header(path)
            rel = path.relative_to(ROOT).as_posix()
            out.append(f"| `{rel}` | {cell(info.get('Purpose'))} | {cell(info.get('Chip'))} | {cell(info.get('Requires'))} |")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def main():
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/CATALOG.md is stale - run: python scripts/gen-catalog.py")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
