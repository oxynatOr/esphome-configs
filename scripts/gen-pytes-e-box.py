#!/usr/bin/env python3
"""Generates hardware/batteries/pytes-e-box.yaml (16 cells x 8 entities) and its txt_pytes_* keys.

Usage: python scripts/gen-pytes-e-box.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TXT = {}
CELLS = range(16)

CELL_TEXT = [("base_state", "Base State"), ("voltage_state", "Voltage State"),
             ("current_state", "Current State"), ("temperature_state", "Temperature State")]
BATTERY_TEXT = CELL_TEXT + [
    ("barcode", "Barcode"), ("dev_type", "Device Type"), ("firm_version", "Firm Version"),
    ("coulomb_status", "Coulomb State"), ("bat_status", "Battery State"), ("cmos_status", "CMOS Status"),
    ("dmos_status", "DMOS Status"), ("bat_protect_ena", "BAT Protect ENA"),
    ("pwr_protect_ena", "PWR Protect ENA"), ("bat_events", "Battery Events"),
    ("power_events", "Power Events"), ("system_fault", "System Fault")]
CELL_NUM = [("voltage", "Voltage"), ("temperature", "Temperature"), ("coulomb", "Coulomb"), ("current", "Current")]
BATTERY_NUM = [
    ("voltage", "Voltage"), ("current", "Current"), ("coulomb", "State of Charge"),
    ("temperature", "Temperature"), ("temperature_low", "Temperature Low"),
    ("temperature_high", "Temperature High"), ("voltage_low", "Voltage Low"),
    ("voltage_high", "Voltage High"), ("work_status", "Work Status"), ("soc_voltage", "SOC Voltage"),
    ("total_coulomb", "Total Coulomb"), ("real_coulomb", "Real Coulomb"),
    ("total_power_in", "Total Power In"), ("total_power_out", "Total Power Out"), ("cell_count", "Cells")]

# value maps applied to text sensors (battery level)
MAPS = {
    "base_state": ["Dischg -> Discharge"],
    "bat_status": ["0x00 -> normal", "0x01 -> maintenance", "0x02 -> Low Battery", "0x04 -> End of Life"],
}
CELL_MAPS = {"base_state": MAPS["base_state"]}

HEADER = """# Purpose:       Pytes E-Box battery as its own sub-device: 16 cells (voltage, temperature, coulomb, current, states) plus battery totals and status texts.
# Requires:      the pytes_e_box external component and its hub (https://github.com/oxynatOr/esphome-pytes_e_box), i18n/en.yaml
# Chip:          any
# Substitutions:
#   pytes_e_box_id:        pytes_e_box_hub - hub id
#   pytes_battery_num:     1 - battery number; the sub-device is 'Battery 1' (include once per battery with vars)
#   pytes_battery_prefix:  Battery - name of the sub-device (without the number)
#   pytes_cell_prefix:     Cell    - name prefix of the cell entities ('Cell 3 Voltage')
# Currents are in mA, as delivered by the component.
# Generated by scripts/gen-pytes-e-box.py - do not edit by hand, change the script.
substitutions:
  pytes_e_box_id: pytes_e_box_hub
  pytes_battery_num: "1"
  pytes_cell_prefix: Cell
  pytes_battery_prefix: Battery

esphome:
  devices:
    - id: battery_${pytes_battery_num}
      name: "${pytes_battery_prefix} ${pytes_battery_num}"

"""

DEVICE = "device_id: battery_${pytes_battery_num}"


def snake(s):
    return re.sub(r"[^a-z0-9]+", "_", s.lower()).strip("_")


def entity(field, label, indent, cell=None, maps=None):
    """one entity block: name, device_id and an optional value map"""
    key = f"txt_pytes_{snake(label)}"
    TXT[key] = label
    pad = " " * indent
    name = f'"${{pytes_cell_prefix}} {cell} ${{{key}}}"' if cell is not None else f"${{{key}}}"
    lines = [f"{' ' * (indent - 2)}{field}:", f"{pad}name: {name}", f"{pad}{DEVICE}"]
    if maps:
        lines += [f"{pad}filters:", f"{pad}  - map:"] + [f"{pad}      - {m}" for m in maps]
    return lines


def platform(kind):
    return [f"{kind}:", "  - platform: pytes_e_box", "    pytes_e_box_id: ${pytes_e_box_id}",
            "    battery: ${pytes_battery_num}", "    cells:"]


def build():
    ts = platform("text_sensor")
    for n in CELLS:
        ts.append(f"      - cell: {n}")
        for field, label in CELL_TEXT:
            ts += entity(field, label, 10, cell=n, maps=CELL_MAPS.get(field))
    for field, label in BATTERY_TEXT:
        ts += entity(field, label, 6, maps=MAPS.get(field))

    ss = platform("sensor")
    for n in CELLS:
        ss.append(f"      - cell: {n}")
        for field, label in CELL_NUM:
            ss += entity(field, label, 10, cell=n)
    for field, label in BATTERY_NUM:
        ss += entity(field, label, 6)
    return HEADER + "\n".join(ts) + "\n\n" + "\n".join(ss) + "\n"


def main():
    out = ROOT / "hardware/batteries/pytes-e-box.yaml"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(build(), encoding="utf-8", newline="\n")
    en = ROOT / "i18n/en.yaml"
    cur = en.read_text(encoding="utf-8")
    add = "".join(f"  {k}: {v}\n" for k, v in sorted(TXT.items()) if f"  {k}:" not in cur)
    en.write_text(cur.rstrip("\n") + "\n" + add, encoding="utf-8", newline="\n")
    print("wrote", out.relative_to(ROOT), "and", len([k for k in TXT if f"  {k}:" not in cur]), "new text keys")


if __name__ == "__main__":
    main()
